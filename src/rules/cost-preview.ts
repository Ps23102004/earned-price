// Cost preview for a merchant (F11): run a rule over a recorded sample of anonymised accounts. Pure, deterministic.
// The dataset is a rough convenience sample, not a statement about GitHub as a whole; callers label it with its date.

import type { GithubSnapshot } from "../facts/types";
import { evaluate } from "./evaluate";
import type { Rule } from "./types";

export type TierShare = { tierId: string; label: string; discountPercent: number; count: number };
export type CostPreview = {
  n: number;
  qualifying: number;
  /** Whole percent of the sample that earns any discount (0 when the sample is empty). */
  sharePercent: number;
  /** Mean discount across the whole sample, one decimal. */
  averageDiscountPercent: number;
  /** Discount given away per 1,000 sales at the list price if buyers looked like this sample (integer cents). */
  giveawayPer1000Cents: number;
  tiers: TierShare[];
  /** Sentence generated by code, never by a model. */
  summary: string;
};

export function costPreview(rule: Rule, accounts: GithubSnapshot[], recordedAt: string, listCents = 4900): CostPreview {
  const clock = new Date(recordedAt);
  const tiers: TierShare[] = rule.tiers.map((t) => ({ tierId: t.id, label: t.label, discountPercent: t.discountPercent, count: 0 }));
  let qualifying = 0;
  let totalPercent = 0;
  for (const a of accounts) {
    const hit = evaluate(rule, a, clock).appliedTierId;
    const tier = tiers.find((t) => t.tierId === hit);
    if (!tier) continue;
    tier.count++;
    qualifying++;
    totalPercent += tier.discountPercent;
  }
  const n = accounts.length;
  const sharePercent = n === 0 ? 0 : Math.round((qualifying / n) * 100);
  const averageDiscountPercent = n === 0 ? 0 : Math.round((totalPercent / n) * 10) / 10;
  const giveawayPer1000Cents = n === 0 ? 0 : Math.round((totalPercent * listCents * 1000) / (100 * n));
  const day = recordedAt.slice(0, 10);
  const summary =
    n === 0
      ? "No sample accounts are available."
      : `About ${sharePercent}% of the ${n} sampled accounts would earn a discount, and the average discount across all ${n} (counting those who get none) is ${averageDiscountPercent}%. Rough sample of GitHub developers with a public repository, recorded ${day}; not all of GitHub and not your customers.`;
  return { n, qualifying, sharePercent, averageDiscountPercent, giveawayPer1000Cents, tiers, summary };
}
